def _format_products(products: list[dict]) -> str:
    sections = []
    for product in products:
        lines = [f"สินค้า: {product['product_name']}"]
        if product.get("aliases"):
            lines.append(f"ชื่อเรียกอื่น: {', '.join(product['aliases'])}")

        lines.append("ขนาดและราคาโปรโมชั่น:")
        for v in product.get("variations", []):
            lines.append(
                f"  • {v['size']} = {v['promo_price']} บาท (จากปกติ {v['regular_price']} บาท) — {v.get('description', '')}"
            )

        ship = product.get("shipping_rules")
        if ship:
            lines.append("กติกาค่าจัดส่ง:")
            std = ship.get("standard", {})
            lines.append(
                f"  • ปกติ: โอนเงิน {std.get('transfer_fee')} บาท / เก็บเงินปลายทาง (COD) {std.get('cod_fee')} บาท"
            )
            promo = ship.get("promotion_1kg_up")
            if promo:
                lines.append(
                    f"  • พิเศษ ({promo.get('condition')}): "
                    f"โอนเงิน {promo.get('transfer_fee')} บาท (ส่งฟรี!) / เก็บเงินปลายทาง (COD) {promo.get('cod_fee')} บาท"
                )
            if ship.get("delivery_time"):
                lines.append(f"  • ระยะเวลาจัดส่ง: {ship['delivery_time']}")

        sections.append("\n".join(lines))
    return "\n\n".join(sections)


def _format_knowledge_base(kb: dict) -> str:
    parts = []
    if kb.get("selling_points"):
        parts.append("จุดเด่นสินค้า:\n" + "\n".join(f"• {s}" for s in kb["selling_points"]))
    if kb.get("usage_instructions"):
        parts.append("วิธีทำ (ตัก-เติม-รอ):\n" + "\n".join(f"• {s}" for s in kb["usage_instructions"]))
    if kb.get("faq"):
        faq = "\n".join(f"• ถาม: {f['question']}\n  ตอบ: {f['answer']}" for f in kb["faq"])
        parts.append("คำถามที่พบบ่อย (FAQ):\n" + faq)
    if kb.get("strict_compliance_rules"):
        rules = "\n".join(f"• {r}" for r in kb["strict_compliance_rules"])
        parts.append("กฎเหล็กของแบรนด์ (ต้องปฏิบัติตาม 100%):\n" + rules)
    return "\n\n".join(parts)


