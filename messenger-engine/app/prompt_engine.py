"""Dynamic Prompting Engine.

Builds the LLM system prompt entirely from config.json at startup. The
scaffolding (role, rules, output contract) is fixed; every brand-specific
fact is interpolated, so the same code serves any brand across LINE OA,
Facebook Messenger, Instagram DM, and Web Chat.
"""

